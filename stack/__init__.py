TEMPLATES = {
    "main": template.template,
    "eks-updates": template.updates_template,
}


def render(stack_name):
    """Return the generated YAML for one template, with the build header."""
    lines = [
        "# This Cloudformation stack template was generated by",
        "# https://github.com/caktus/aws-web-stacks",
        "# at %s" % datetime.datetime.now(),
        "# with parameters:",
    ]
    parms_used = sorted(
        parm for parm in os.environ.keys()
        if parm.startswith("USE_") or parm in ("DEFAULTS_FILE", "EMIT_STACK")
    )
    for parm in parms_used:
        lines.append("#\t%s = %s" % (parm, os.environ[parm]))
    lines.append("")
    return "\n".join(lines) + TEMPLATES[stack_name].to_yaml()


# Emit one template per build. EMIT_STACK selects which one (default "main");
# see the Makefile for the full set.
